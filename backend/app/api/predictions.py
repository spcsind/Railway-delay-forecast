from fastapi import APIRouter, HTTPException

from app.db.database import SessionLocal
from app.db.models import Train
from app.schemas.train import TrainPrediction
from app.services.simulator import latest_train_state


router = APIRouter(
    prefix="/predictions",
    tags=["Predictions"]
)


@router.get("/{train_number}", response_model=TrainPrediction)
def get_train_prediction(train_number: str):

    db = SessionLocal()

    try:
        train = (
            db.query(Train)
            .filter(Train.train_number == train_number)
            .first()
        )
    finally:
        db.close()

    if train is None:
        raise HTTPException(
            status_code=404,
            detail="Train not found"
        )

    # Get latest state generated by simulator + ML
    train_state = latest_train_state.get(train_number)

    if train_state is None:
        raise HTTPException(
            status_code=503,
            detail="Live train state not available yet"
        )

    current_delay = train_state["current_delay"]
    predicted_delay = train_state["predicted_delay"]

    delay_change = (
        predicted_delay - current_delay
    )

    return {
        "train_number": train_state["train_number"],
        "next_station": "Jalandhar",
        "current_delay_minutes": current_delay,
        "predicted_delay_minutes": predicted_delay,
        "delay_change_minutes": delay_change,
        "predicted_eta": train_state["predicted_eta"],
        "lower_eta": None,
        "upper_eta": None,
        "model_version": "train_eta_proto_v1",
    }